export function normalizeLocale(value) {
  const raw = String(value || '').trim().toLowerCase();
  return raw.startsWith('vi') ? 'vi' : 'en';
}

function interpolate(value, vars = {}) {
  return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : `{${key}}`
  ));
}

export function translate(locale, key, vars = {}) {
  const lang = normalizeLocale(locale);
  const value = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  return interpolate(value, vars);
}

export function statusLabel(locale, value) {
  if (value == null || value === '') return '-';
  const key = `status.${String(value).toLowerCase()}`;
  const translated = translate(locale, key);
  return translated === key ? String(value) : translated;
}

export function eventTypeLabel(locale, value) {
  if (!value) return '-';
  const key = `event.${String(value).toUpperCase()}`;
  const translated = translate(locale, key);
  return translated === key ? String(value) : translated;
}

export function setLanguage(locale) {
  const lang = normalizeLocale(locale);
  if (typeof document !== 'undefined') {
    document.cookie = `qport_lang=${lang}; Path=/; Max-Age=31536000; SameSite=Lax`;
  }
  if (typeof window !== 'undefined') window.location.reload();
}

export function useI18n(locale = 'en') {
  const lang = normalizeLocale(locale);
  return {
    locale: lang,
    t: (key, vars) => translate(lang, key, vars),
    status: (value) => statusLabel(lang, value),
    eventType: (value) => eventTypeLabel(lang, value),
    setLanguage,
  };
}
